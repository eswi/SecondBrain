import SwiftUI

/// **수집 화면에 어떻게 들어왔나** — **나가는 뜻이 갈린다**(2026-08-31 사용자 결정).
///
/// 사용자: *"살아있는 기억 화면에서 + 기호 눌러서 수집 화면으로 들어온 경우는 `<` 아이콘이 존재해야
/// 하고 의미가 있지만 (되돌아간다는) 취소하기는 좀 더 확장된 의미야. 앱 밖에서 핫키 눌러서 들어온
/// 경우는 그냥 앱을 종료시켜야 해. … 이 경우 `<` 아이콘은 없어야 하고 취소하기 누르면 그냥 앱 밖으로
/// 나가야 해."*
///
/// ★ **그래서 `<`는 「되돌아간다」이고 [취소하기]는 「이 수집을 그만둔다」다** — 앱 안에서는 둘이 같은
/// 곳으로 가지만 **뜻이 다르다.**
///
/// ## ⛔ **`<`는 어떻게 들어왔든 늘 있다** (2026-08-31 사용자가 다시 정했다)
/// > *"어떤 식으로 진입을 하더라도 수집 화면에서는 `<` 기호를 두기로 하고, 앱 밖에서 바로 수집
/// > 화면으로 들어온 경우 `<` 기호를 누르면 '새로운 기억' 화면으로 가기로 하자."*
///
/// **옛 서술(지우지 않는다 · 반나절 만에 뒤집혔다):** *"핫키로 들어오면 돌아갈 화면이 없으므로
/// `<`가 아예 없다."* — **돌아갈 화면이 없는 것이 아니라 「새로운 기억」이 그 자리였다.**
///
/// | 들어온 길 | `<` | [취소하기] |
/// |---|---|---|
/// | **`.inApp`** | 있다 → **온 화면으로** | 수집을 그만두고 **온 화면으로** |
/// | **`.hotkey`** | 있다 → **「새로운 기억」으로** | **앱 밖으로** |
///
/// ★ **그래서 갈리는 것은 [취소하기] 하나다** — `<`는 둘 다 「앱 안에 머문다」다.
enum CaptureOrigin {
    /// 앱 안에서 `+`를 눌러 들어왔다 — 나가면 **그 화면으로 되돌아간다.**
    case inApp
    /// 앱 밖에서 액션 버튼·단축어(핫키)로 들어왔다 — 나가면 **앱 밖으로 나간다.**
    case hotkey
}

/// 앱 밖(액션 버튼·단축어)에서 "수집 시트를 열어라"를 앱에 전달하는 공유 신호.
/// App Intent가 `requestCapture()`를 부르면 RootView가 관찰해 CaptureSheet를 띄운다.
@MainActor
final class CaptureLauncher: ObservableObject {
    static let shared = CaptureLauncher()
    private init() {}

    @Published var showCapture = false

    // ⛔ **옛 값(2026-09-02에 지웠다): `processStarted`** — *"이 프로세스가 언제 떴나"*.
    //    **3초 문턱의 밑값**이었고, 그 문턱이 죽으면서 함께 쓸 데가 없어졌다(아래 `wokenByHotkey`).

    /// **앱이 이 URL 때문에 「떴다」** — 따뜻한 진입(이미 떠 있는데 URL이 온 것)과 갈린다.
    ///
    /// ★★ **왜 갈라야 하나** (2026-08-31): 옵션은 첫 프레임 전에 알지만
    /// **`fullScreenCover`는 「띄우는 것」이라 한 프레임 뒤에 올라온다** — 그래서
    /// **목록이 짧게 스쳤다**(사용자: *"짧은 시간동안 새로운 기억 화면이 띄긴 하네. 짧게."*).
    /// ✅ **띄우지 않고 「뿌리로」 그리면 스칠 자리가 없다** — 같은 프레임에 그려진다.
    /// ⛔ **따뜻한 진입은 뿌리로 바꾸면 안 된다** — 이미 화면이 있고, 갑자기 뿌리가 바뀌면
    /// **그 화면이 사라진다.** 그 길은 그대로 `fullScreenCover`다.
    var launchedByURL = false

    /// 핫키로 열 때 **그 순간의 탭** — [취소하기]로 나갈 때 **그 화면으로 되돌린다**(2026-08-31 사용자:
    /// *"앱이 그 전에 suspend되어 있던 화면 상태로 suspend"*). `RootView`가 넣고 `RootView`가 쓴다.
    var tabBeforeHotkey: AppTab?

    /// **핫키가 앱을 깨웠나 — 짐작이 아니라 사실이다** (2026-09-02에 뒤집었다).
    ///
    /// ★★ **`launchedByURL`이 그 사실 자체다** — `AppLaunchOptions`가 **scene이 연결될 때**
    /// (`configurationForConnecting`) 켠 값이라 **「이 URL 때문에 앱이 떴다」**를 뜻한다.
    /// 앱이 이미 떠 있는데 URL이 오면 그 길은 `onOpenURL`이고 이 값은 **안 켜진다.**
    ///
    /// ⛔⛔ **옛 꼴(뒤집혔다) — 시간으로 짐작했다:**
    /// *"`Date().timeIntervalSince(processStarted) < 3.0`"* — 프로세스가 뜬 뒤 3초 안에 오면
    /// 깨운 것으로 봤다. **2026-09-02에 폰에서 깨졌다:** 사용자가 **앱을 완전히 끝내고 단축키로 들어와
    /// 3초 넘게 머문 뒤** [취소하기]를 누르니 **깨운 것으로 안 봐서 앱이 안 끝났다.**
    /// ★ **문턱이 잰 시간이 아니라 「사용자가 화면에 머무는 시간」과 겨루고 있었다** —
    /// 그쪽은 얼마든지 길어질 수 있으므로 **어떤 값을 골라도 틀린다.**
    /// ★★ **08-31 worklog §2가 이 형태에 이름을 붙여 뒀다** —
    /// 「짐작한 상수로 경합을 덮으려 한 것」(`350ms`·`120ms`·`3.0s`). **셋째가 여기서 죽었다.**
    /// ▶ **가름은 그때 적어 둔 그대로였다:** *"이 값을 짐작해야 하나? 그 사실을 알려주는 신호가 없나?"*
    var wokenByHotkey: Bool { launchedByURL }

    /// ⛔ **옛 이름(2026-09-02에 지웠다): `likelyWokenByHotkey`** — 「likely」가 붙어 있던 이유가
    /// 추정이었기 때문이고, **지금은 추정이 아니다.**
    ///
    /// 사용자 결정(2026-08-31): *"앱이 그 전에 suspend되어 있던 화면 상태로 suspend.
    /// 아예 앱이 exit 상태였다면 exit상태로."* → **깨운 것이면 끝내고, 이미 떠 있었으면 내려놓는다.**
    ///
    /// ⛔ **「앱이 그 전에 떠 있었나」를 딱 잘라 아는 공개 API가 없다.** 그래서 **프로세스가 뜬 뒤
    /// 얼마나 지났는지**로 가른다 — 콜드 런치면 수집 요청이 **거의 즉시** 오고, 이미 쓰고 있었다면
    /// 그만큼 시간이 지나 있다.
    /// ⚠️ **문턱 3초는 잰 값이 아니라 고른 값이다**(추정). **틀리는 방향이 둘 다 가볍다:**
    /// **① 앱을 켠 직후(3초 안) 핫키를 누르면** 깨운 것으로 봐 **끝낸다**(사용자가 다시 열면 된다) ·
    /// **② 시작이 3초를 넘게 걸리면** 이미 떠 있던 것으로 봐 **내려놓는다**(끝나지 않는다).
    /// ⛔ **`exit(0)` 쪽이 더 비싼 오판이므로**(크래시로 기록된다) 문턱을 **짧게** 잡았다.
    /// ⛔ **옛 장치(2026-09-02에 하루 만에 걷어냈다): `holdForExit`** — 화면이 내려간 **뒤에**
    /// 다시 붙잡으려 했다. **폰에서 안 통했다**(사용자: *"3번은 전혀 안 바뀌었음"*) —
    /// `suspend`가 **그 갱신보다 먼저** 화면을 떠 가기 때문이다.
    /// ★ **답은 붙잡는 것이 아니라 「내리지 않는 것」이었다** — `CaptureSheet.leaveNow`가
    /// 끝내는 길에서는 `showCapture`를 **아예 안 내린다.**

    /// **수집이 [취소하기]로 닫혔나** — `RootView`가 「앱 밖으로」를 할지 정하는 데 쓴다.
    /// ⛔ **`<`로 닫히면 이 값이 안 켜진다** — `<`는 **앱 안에 머무는** 뜻이다.
    /// ⚠️ **RootView가 쓰고 나서 반드시 내린다** — 안 내리면 다음 닫힘에서 앱이 나가 버린다.
    /// ★★ **`@Published`다 — `RootView`가 이 값의 변화로 움직인다** (2026-09-02).
    /// ⛔ **`showCapture`가 내려가는 것으로는 못 움직인다** — **끝내는 길에서는 그 값이 안 내려가기
    /// 때문**이다(내리면 목록이 드러난다). 그래서 **닫힘의 신호를 이 값으로 옮겼다.**
    @Published var cancelledOut = false

    /// ★ **애니메이션 없이 띄운다** (2026-08-31 사용자: *"지금은 핫키 눌러서 앱에 진입하면 첫 화면
    /// 띄운 후 수집 화면으로 들어오지만 내 의도대로라면 바로 수집 화면으로 들어와야 해."*)
    ///
    /// ⚠️ **첫 프레임이 목록인 것 자체는 못 없앤다** — 앱이 떠야 인텐트가 돌고, 그 뒤에 시트가 뜬다.
    /// **없앨 수 있는 것은 「미끄러져 올라오는 동작」**이고, 그것을 없애면 **목록이 스쳐 보이는 시간이
    /// 애니메이션 길이(≈0.35초)만큼 줄어든다.** ⛔ **「바로」의 나머지는 앱 시작 시간이다.**
    /// - Parameter fromLaunch: **앱이 이 요청 때문에 떴나**(런치 옵션에서 왔나).
    ///   `true`면 수집 화면이 **뿌리로** 그려진다(`launchedByURL`).
    func requestCapture(fromLaunch: Bool = false) {
        if fromLaunch { launchedByURL = true }
        var t = Transaction()
        t.disablesAnimations = true
        withTransaction(t) { showCapture = true }
    }

}
